#!/bin/bash
# Блокировки при сборке мусора в дереве вхождений обратного индекса.
#
# МЕХАНИЗМ (по коммиту 218f51584d5). До изменения ginVacuumPostingTreeLeaves
# берёт LockBufferForCleanup на корне дерева вхождений В НАЧАЛЕ прохода и
# держит его весь рекурсивный спуск. После — блокировка берётся только когда
# найдена подлежащая удалению пустая страница.
#
# ОТСЮДА ПОСТАНОВКА. Мерить пропускную способность под нагрузкой из многих
# клиентов незачем: величина зависит от числа клиентов и планировщика ОС.
# Достаточно ОДНОГО читателя, и вопрос ставится узко:
#
#   Случай A — удалять нечего (удалено 0,1 % строк вразброс, ни одна страница
#   дерева вхождений не опустела). До изменения корень всё равно блокируется
#   на весь проход, после — не блокируется вовсе. Это то изменение, которое
#   уцелело после отката и работает сегодня.
#
#   Случай B — удалять есть что (удалена непрерывная половина таблицы, отчего
#   опустевают целые страницы дерева вхождений: элементы в нём упорядочены по
#   ссылке на строку, то есть по порядку таблицы).
#
# Второй оптимизации (блокировать поддерево, а не всё дерево) здесь нет
# намеренно: она отменена, и мерить её выигрыш значило бы мерить то, чего у
# пользователя нет. Существенна в ней взаимная блокировка — свойство
# корректности, а не производительности.
#
# ЧЕМ ПРОБОВАТЬ. Не полным просмотром по ключу: он читает всё дерево вхождений
# целиком, стоит секунды сам по себе и тонет в собственной стоимости. Пробой
# служит ВСТАВКА строки с тем же ключом — она проходит один путь корень-лист,
# стоит миллисекунды, но упирается в ту же блокировку корня. Это и есть то, что
# делала промышленная нагрузка, из-за которой изменение и писалось: почтовый
# поиск, где письма добавляются непрерывно.
#
# ЧТО ДЕЛАЕТ ЗАДЕРЖКУ ЗАМЕТНОЙ. Блокировка корня держится на время спуска по
# всем листьям дерева вхождений. В памяти это миллисекунды, и эффекта не видно
# (первая редакция замера показала 0,001 с при обеих версиях). Держит
# блокировку чтение страниц, а не задержка по стоимости: точка задержки стоит
# после спуска, а не внутри него. Поэтому буферный кэш мал, дерево вхождений
# велико, а страничный кэш операционной системы сбрасывается перед замером.
#
# ВСТАВКА ДОЛЖНА ИДТИ В ДЕРЕВО, А НЕ В СПИСОК ОТЛОЖЕННЫХ. У обратного индекса
# по умолчанию включено fastupdate: вставка лишь дописывает элемент в список
# отложенных и дерева вхождений не касается вовсе. С ним проба не мерит ничего
# (предыдущая редакция замера показала 0,01 с при обеих версиях). Индекс
# создаётся с fastupdate = off.
set -e
export LANG=C LC_ALL=C
. "$HOME/benchlock.sh"

N=${N:-3000000}
PORT=5464
D=/mnt/nvme/data/ginlock
PAIR=${PAIR:-a}
REP=${REP:-3}

case "$PAIR" in
  a) V0=gin-a0; V1=gin-a1;;
  b) V0=gin-b0; V1=gin-b1;;
  *) echo "PAIR должен быть a или b"; exit 1;;
esac

# fd 9 держит замок и не должен утечь в postmaster: всюду 9>&-
BIN() { echo "$HOME/bench-$1/bin"; }
q() { local n="$1"; shift; "$(BIN $n)/psql" -h /tmp -p $PORT -d postgres -X -q -t -A "$@" 9>&-; }
stop()  { "$(BIN $1)/pg_ctl" -D "$D" -w stop >/dev/null 2>&1 9>&- || true; }
start() { "$(BIN $1)/pg_ctl" -D "$D" -l "$D/pg.log" -w start >/dev/null 9>&-; }

# Проба: вставка строки с тем же ключом. Один путь корень-лист.
PROBE="INSERT INTO gt VALUES (ARRAY[42, (random()*100000)::int], -1)"

init_for() {
  local v=$1
  stop "$v"; rm -rf "$D"
  "$(BIN $v)/initdb" -D "$D" --locale=C --encoding=UTF8 >/dev/null 2>&1 9>&-
  {
    echo "port = $PORT"; echo "shared_buffers = 64MB"; echo "maintenance_work_mem = 256MB"
    echo "max_wal_size = 4GB"; echo "autovacuum = off"
    echo "listen_addresses = ''"; echo "unix_socket_directories = '/tmp'"
  } >> "$D/postgresql.conf"
  start "$v"
  # Ключ 42 — в каждой строке: одно большое дерево вхождений, ради которого всё
  # и затевается. Пробой служит вставка, так что избирательность ключа роли не
  # играет и подстраиваться под планировщик не нужно.
  q "$v" -c "SELECT setseed(0.5);
      CREATE TABLE gt AS
        SELECT ARRAY[42, (random()*100000)::int] AS a, i
        FROM generate_series(1,$N) i" >/dev/null
  q "$v" -c "CREATE INDEX gti ON gt USING gin (a) WITH (fastupdate = off)" >/dev/null
  q "$v" -c "VACUUM ANALYZE gt" >/dev/null
}

bench_lock
bench_preflight

printf 'версия|случай|базовая вставка, с|макс. вставка при сборке, с|блокировка, с|сборка мусора, с|страниц индекса\n'
for v in $V0 $V1; do
  [ -x "$(BIN $v)/postgres" ] || { echo "$v: сборки нет, пропуск" >&2; continue; }
  for case_ in A B; do
    for r in $(seq 1 $REP); do
      init_for "$v"
      if [ "$case_" = A ]; then
        q "$v" -c "DELETE FROM gt WHERE i % 1000 = 0" >/dev/null      # вразброс, страницы не пустеют
      else
        q "$v" -c "DELETE FROM gt WHERE i <= $((N/2))" >/dev/null     # непрерывно, страницы пустеют
      fi
      q "$v" -c "CHECKPOINT" >/dev/null
      stop "$v"; sync; sudo -n sh -c 'echo 3 > /proc/sys/vm/drop_caches'; start "$v"

      BASE=$(for k in 1 2 3 4 5; do
               s=$(date +%s.%N); q "$v" -c "$PROBE" >/dev/null; e=$(date +%s.%N)
               awk -v a="$s" -v b="$e" 'BEGIN{printf "%.3f\n", b-a}'
             done | sort -n | head -1)

      RO=$(mktemp); : > "$RO"
      ( while :; do
          s=$(date +%s.%N)
          "$(BIN $v)/psql" -h /tmp -p $PORT -d postgres -X -q -t -A -c "$PROBE" >/dev/null 2>&1 9>&-
          e=$(date +%s.%N)
          awk -v a="$s" -v b="$e" 'BEGIN{printf "%.3f\n", b-a}' >> "$RO"
        done ) & RPID=$!
      sleep 1
      T0=$(date +%s.%N)
      q "$v" -c "VACUUM gt" >/dev/null
      T1=$(date +%s.%N)
      kill "$RPID" 2>/dev/null || true; wait "$RPID" 2>/dev/null || true
      MAXQ=$(sort -n "$RO" | tail -1); NQ=$(wc -l < "$RO"); rm -f "$RO"

      printf '%s|%s|%s|%s|%s|%s|%s\n' "$v" "$case_" "$BASE" "${MAXQ:-0}" \
        "$(awk -v a="${MAXQ:-0}" -v b="$BASE" 'BEGIN{printf "%.3f", a-b}')" \
        "$(awk -v a="$T0" -v b="$T1" 'BEGIN{printf "%.1f", b-a}')" \
        "$(q "$v" -c "select pg_relation_size('gti')/8192")"
    done
  done
  stop "$v"
done

bench_postflight
